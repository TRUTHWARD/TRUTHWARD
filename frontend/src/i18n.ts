export function t(locale: Locale, key: keyof typeof dictionaries["en-US"]) {
  return dictionaries[locale][key] ?? dictionaries["en-US"][key] ?? key;
}

export function formatT(
  locale: Locale,
  key: string,
  parameters: Record<string, string | number | boolean | null> = {},
  fallbackKey = "executionExplanationUnknownKey",
) {
  const template =
    dictionaries[locale][key]
    ?? dictionaries["en-US"][key]
    ?? dictionaries[locale][fallbackKey]
    ?? dictionaries["en-US"][fallbackKey]
    ?? fallbackKey;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, parameterName: string) => {
    const value = parameters[parameterName];
    return value === undefined || value === null ? match : String(value);
  });
}
